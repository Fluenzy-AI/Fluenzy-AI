export function isHRNavItemActive(pathname: string, item: HRNavItem): boolean {
  if (!pathname) return false;
  const cleanPath = pathname.replace(/\/$/, "");
  const cleanHref = item.href.replace(/\/$/, "");

  // Dashboard special case: /portal/hr or /portal/hr/dashboard
  if (item.id === "dashboard") {
    return cleanPath === "/portal/hr" || cleanPath === "/portal/hr/dashboard";
  }

  // Exact match with primary href
  if (cleanPath === cleanHref) return true;

  // Exact match with any alias
  if (item.aliases && item.aliases.some((alias) => cleanPath === alias.replace(/\/$/, ""))) {
    return true;
  }

  // Sub-route match (e.g. /portal/hr/employees/new matches /portal/hr/employees)
  if (cleanHref !== "/portal/hr" && cleanPath.startsWith(cleanHref + "/")) {
    return true;
  }
  if (item.aliases) {
    for (const alias of item.aliases) {
      const cleanAlias = alias.replace(/\/$/, "");
      if (cleanAlias !== "/portal/hr" && cleanPath.startsWith(cleanAlias + "/")) {
        return true;
      }
    }
  }

  return false;
}
